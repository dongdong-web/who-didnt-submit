def w_docx(path: Path, name: str, sid: str, title: str) -> None:
    doc = Document()
    doc.add_heading(title, level=1)
    if sid:
        doc.add_paragraph(f"编号：{sid}")
    if name:
        doc.add_paragraph(f"姓名：{name}")
    doc.add_paragraph("")
    doc.add_paragraph("一、实验目的")
    doc.add_paragraph("掌握结构化分析方法，完成需求规格说明与数据流图设计。")
    doc.add_paragraph("二、实验内容")
    doc.add_paragraph("针对图书管理系统完成顶层数据流图与一层分解。")
    doc.add_paragraph("三、实验结论")
    doc.add_paragraph("掌握了自顶向下、逐层分解的分析方法。")
    doc.save(str(path))


def w_pdf(path: Path, name: str, sid: str) -> None:
    """Pillow 能直接存 PDF，生成出来是真实可打开的 PDF。"""
    Image.new("RGB", (595, 842), "white").save(str(path), "PDF", resolution=72)


def w_zip(path: Path, name: str, sid: str) -> None:
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("说明.txt", f"姓名：{name}\n编号：{sid}\n（附件为实验报告）\n")


def w_img(path: Path) -> None:
    Image.new("RGB", (600, 400), (232, 234, 237)).save(str(path))


def w_text(path: Path, name: str, sid: str) -> None:
    path.write_text(f"姓名：{name}\n编号：{sid}\n", encoding="utf-8")


def w_book(path: Path, name: str, sid: str) -> None:
    """真的 .xlsx —— 老师自己放在文件夹里的那种表。"""
    wb = Workbook()
    ws = wb.active
    ws.append(["姓名", "成绩"])
    if name:
        ws.append([name, 90])
    wb.save(str(path))


def emit(path: Path, name: str = "", sid: str = "", title: str = "") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    ext = path.suffix.lower()
    if ext == ".docx":
        w_docx(path, name, sid, title or "实验报告")
    elif ext == ".pdf":
        w_pdf(path, name, sid)
    elif ext == ".zip":
        w_zip(path, name, sid)
    elif ext in (".xlsx", ".xlsm"):
        w_book(path, name, sid)
    elif ext in (".jpg", ".jpeg", ".png"):
        w_img(path)
    else:  # .doc / .db / .DS_Store 之类，写占位文本即可
        w_text(path, name, sid)


def write_xlsx(path: Path, header: list[str], rows: list[tuple]) -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "名单"
    ws.append(header)
    for r in rows:
        ws.append(list(r))
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(str(path))


