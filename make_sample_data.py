def build_scenario_a() -> None:
    base = ROOT / "场景A_大学班级收作业"
    write_xlsx(
        base / "全班名单.xlsx", ["学号", "姓名"],
        [(sid, name) for sid, name in A_ROSTER],
    )
    for rel, name, sid in A_FILES:
        emit(base / "收到的作业" / rel, name, sid, "软件工程实验报告")

    # 班长打包发来的汇总：没有个人署名，所以读内容也认不出是谁。
    # 这种「一个包装着全班作业」是内容匹配的天然盲区。
    with zipfile.ZipFile(base / "收到的作业" / "全班作业汇总.zip", "w") as z:
        z.writestr("说明.txt", "本压缩包为全班作业汇总，共 52 份，请老师查收。\n")

    # 打上修改时间，模拟真实的微信目录时间线：
    #   1月3日 收作业、1月4日 有人补交、1月10日 班长发了汇总，
    #   而那份成绩表是老师上个月自己放进去的。
    hall = base / "收到的作业"
    stamps = {}
    for p in hall.rglob("*"):
        if p.is_file():
            stamps[p] = datetime(2026, 1, 3, 10, 0)

    for name in ("刘洋.docx", "万里.docx", "于洋.docx", "余波.docx", "侯亮作业.docx"):
        if (hall / name).exists():
            stamps[hall / name] = datetime(2026, 1, 4, 21, 30)

    for name, when in (("全班作业汇总.zip", datetime(2026, 1, 10, 9, 0)),
                       ("期末成绩汇总.xlsx", datetime(2025, 12, 20, 15, 0))):
        if (hall / name).exists():
            stamps[hall / name] = when

    for p, when in stamps.items():
        t = when.timestamp()
        os.utime(p, (t, t))

    (base / "预期结果.md").write_text(A_EXPECT, encoding="utf-8")


